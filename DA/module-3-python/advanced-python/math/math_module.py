import math

# Math constants
print("pi =", math.pi)
print("e =", math.e)
print("tau =", math.tau)

# Rounding functions
print("floor(245.6565) =", math.floor(245.6565))
print("ceil(245.6565) =", math.ceil(245.6565))
print("trunc(245.6565) =", math.trunc(245.6565))

# Factorial and power
print("factorial(5) =", math.factorial(5))
print("sqrt(81) =", math.sqrt(81))
print("pow(2, 10) =", math.pow(2, 10))
print("gcd(48, 18) =", math.gcd(48, 18))
print("lcm(12, 18) =", math.lcm(12, 18))

# Logarithms
print("log(100) =", math.log(100))
print("log10(1000) =", math.log10(1000))
print("log2(8) =", math.log2(8))

# Trigonometry
print("sin(pi/2) =", math.sin(math.pi / 2))
print("cos(0) =", math.cos(0))
print("tan(pi/4) =", math.tan(math.pi / 4))

# Degree conversion
angle_in_degrees = 60
print("60 degrees in radians =", math.radians(angle_in_degrees))
print("pi/3 in degrees =", math.degrees(math.pi / 3))
print("sin(60 degrees) =", math.sin(math.radians(angle_in_degrees)))

# Hypotenuse example
print("hypot(3, 4) =", math.hypot(3, 4))

# Absolute value and integer square root
print("fabs(-7.5) =", math.fabs(-7.5))
print("isqrt(25) =", math.isqrt(25))

